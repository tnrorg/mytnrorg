--  Run once in the Supabase SQL editor.
--
--  WHY THIS IS REQUIRED, NOT OPTIONAL
--
--  The same two CHECK constraints widened for University Ambassadors have to
--  be widened again, because Postgres enforces both on every write:
--
--    membership_members.chk_member_role
--      check (role in ('general','uc_team','cec','advisory','university_ambassador'))
--
--    leadership_profiles.body
--      check (body in ('advisory','executive','ambassador'))
--
--  UNTIL THIS FILE IS RUN, APPOINTING A COUNTRY AMBASSADOR FAILS AT THE
--  DATABASE. That failure is worth spelling out, because last time it was not
--  obvious: the assign route updated the role without checking the error, so
--  25 ambassador profiles existed while 0 members actually held the role, and
--  the public directory labelled every one of them "Advisory Council". The
--  route now checks, and the admin gets a message naming this file — but the
--  appointment still will not stick until it has been run.
--
--  WHY THE UNIVERSITY BODY IS STILL CALLED 'ambassador'
--
--  It would read better as 'university_ambassador', to match this one. It is
--  deliberately NOT renamed. Renaming it means an UPDATE across the existing
--  live profiles, and if the code shipped before the UPDATE ran, the
--  University Ambassadors section on the home page would go empty in public.
--  A slightly awkward key is a much smaller problem than a roster of real
--  people vanishing from the website. The asymmetry is contained in
--  AMBASSADOR_BODIES / isAmbassadorBody in lib/membership/roles.js, so no
--  other file has to know about it.
-- ════════════════════════════════════════════════════════════════════════════

-- ── 1. The membership role ──────────────────────────────────────────────────
/* Dropped and recreated: a CHECK cannot be altered in place. Both statements
 * run in one implicit transaction, so the table is never briefly left without
 * the constraint — if the ADD fails the DROP rolls back with it.
 *
 * Every value already allowed is repeated here. Leaving one out would not
 * merely fail to add the new role, it would make every existing member
 * holding the omitted role unwritable. */
alter table membership_members drop constraint if exists chk_member_role;

alter table membership_members add constraint chk_member_role
  check (role in (
    'general', 'uc_team', 'cec', 'advisory',
    'university_ambassador', 'country_ambassador'
  ));

-- ── 2. The public roster ────────────────────────────────────────────────────
/* Same DO block as the university migration: the body constraint is an inline
 * column CHECK, so its name was generated by Postgres and may differ between
 * installations. This finds it by definition rather than trusting a name. */
do $$
declare c record;
begin
  for c in
    select con.conname
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    where rel.relname = 'leadership_profiles'
      and con.contype = 'c'
      and pg_get_constraintdef(con.oid) ilike '%body%'
  loop
    execute format('alter table leadership_profiles drop constraint %I', c.conname);
  end loop;
end $$;

alter table leadership_profiles add constraint leadership_profiles_body_check
  check (body in ('advisory', 'executive', 'ambassador', 'country_ambassador'));

-- ── 3. Make the new roster easy to read ─────────────────────────────────────
/* The existing (body, sort_order) index already covers the public query. This
 * is for the opposite direction — "which members are country ambassadors" —
 * which is what the membership screen and the directory filter ask. */
create index if not exists ix_members_country_ambassador
  on membership_members (role) where role = 'country_ambassador';

-- ════════════════════════════════════════════════════════════════════════════
--  VERIFY — run this after the statements above. Both rows should say OK.
-- ════════════════════════════════════════════════════════════════════════════
select
  'member role accepts country_ambassador' as check_name,
  case when pg_get_constraintdef(oid) like '%country_ambassador%' then 'OK' else 'FAILED' end as result
from pg_constraint where conname = 'chk_member_role'
union all
select
  'leadership body accepts country_ambassador',
  case when pg_get_constraintdef(oid) like '%country_ambassador%' then 'OK' else 'FAILED' end
from pg_constraint where conname = 'leadership_profiles_body_check';

